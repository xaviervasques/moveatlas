# -*- coding: utf-8 -*-
"""Bring the movement gallery into the site.

The gallery is the public export of the MD_FM synthetic patient's skeleton catalogue: one self-contained HTML page
(every clip embedded, joint positions only) and its manifest, written by MD_FM's
scripts/render_skeleton_catalogue.py --public. This script copies both into site/source/_static/movement_gallery/
(not tracked: the page is large and regenerated) and writes the counts the page cites into
site/source/_generated/movement_gallery_counts.rst (substitutions) and movement_gallery_groups.html (the table of the
groups), so that every number on the page comes from the manifest. It refuses a manifest that is not a public export
(field "public" true), whose clips do not each state their provenance, that lists a clip built on a motion-capture
take (AMASS EULAs: pointer_only in docs/license_matrix.csv), whose licence is not an open one (LICENCE_PREFIX: the
gallery is rebuilt on the open Anny body model, row anny_body_model of docs/license_matrix.csv, and ships under CC BY
4.0 since 2026-11-15; a non-commercial or no-derivatives licence is refused), or whose page does not match its
sha256. The release scan of build_public_release.py still refuses anything derived from an SMPL family model.

    python site/gen_movement_gallery.py --from <the public gallery folder>

Run from the repo root before the Sphinx build; the build does not run it.
"""
import argparse
import hashlib
import html
import json
import os
import re
import shutil
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(REPO, "site", "source")
STATIC = os.path.join(SOURCE, "_static", "movement_gallery")
GENERATED = os.path.join(SOURCE, "_generated")
PAGE = "movement_gallery.html"
MANIFEST = "movement_gallery_manifest.json"
GENERATED_ONLY = "generated"   # the provenance a gallery clip must state: every frame made by the generator
LICENCE_PREFIX = "CC BY 4.0"   # the gallery's licence (MD_FM plan phase E): open, attribution only


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def check(src):
    """The manifest of the gallery folder src, after the refusals of the module docstring."""
    with open(os.path.join(src, MANIFEST), encoding="utf-8") as f:
        man = json.load(f)
    if man.get("public") is not True:
        sys.exit("refused: the manifest is not a public export (field 'public')")
    prov = man.get("provenance") or {}
    unstated = [c for c in man["clips"] if c not in prov]
    if unstated:
        sys.exit(f"refused: clips without a stated provenance: {unstated}")
    captured = [c for c in man["clips"] if prov[c] != GENERATED_ONLY]
    if captured:
        sys.exit(f"refused: clips not made by the generator alone (a motion-capture take): {captured}")
    lic = str(man.get("licence") or "")
    if (not lic.startswith(LICENCE_PREFIX + " ") or re.search(r"\b(?:NC|ND)\b", lic)
            or re.search(r"non-?commercial|no ?derivatives", lic, re.I)):
        sys.exit(f"refused: the gallery's licence is not {LICENCE_PREFIX}: {lic!r}")
    if sha256(os.path.join(src, PAGE)) != man["page_sha256"]:
        sys.exit("refused: the page does not match its sha256 in the manifest")
    return man


def write_counts(man):
    groups = man["groups"]
    subs = {
        "gallery_n_clips": f"{len(man['clips']):,}",
        "gallery_n_symptom": f"{man['n_symptom_clips']:,}",
        "gallery_n_level0": f"{man['n_level0_clips']:,}",
        "gallery_n_groups": f"{len(groups):,}",
        "gallery_n_left_out": f"{sum(len(v) for v in man['left_out'].values()):,}",
        "gallery_created": man["created_utc"][:10],
        "gallery_mb": f"{man['page_bytes'] / 1e6:.0f}",
    }
    os.makedirs(GENERATED, exist_ok=True)
    with open(os.path.join(GENERATED, "movement_gallery_counts.rst"), "w", encoding="utf-8", newline="\n") as f:
        f.write(".. Generated by site/gen_movement_gallery.py from the gallery manifest; do not edit.\n\n")
        for k, v in subs.items():
            f.write(f".. |{k}| replace:: {v}\n")
    rows = "".join(f"<tr><td>{html.escape(g['name'])}</td><td style=\"text-align:right\">{g['n_clips']}</td>"
                   f"<td>{html.escape(', '.join(g.get('scales', [])))}</td></tr>\n" for g in groups)
    with open(os.path.join(GENERATED, "movement_gallery_groups.html"), "w", encoding="utf-8", newline="\n") as f:
        f.write("<table class=\"table\">\n<thead><tr><th>Group</th><th style=\"text-align:right\">Clips</th>"
                "<th>Scales named in the captions</th></tr></thead>\n<tbody>\n" + rows + "</tbody>\n</table>\n")
    return subs


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--from", dest="src", required=True, help="the public gallery folder written by MD_FM")
    a = ap.parse_args(argv)
    man = check(a.src)
    os.makedirs(STATIC, exist_ok=True)
    for name in (PAGE, MANIFEST):
        shutil.copyfile(os.path.join(a.src, name), os.path.join(STATIC, name))
    subs = write_counts(man)
    print(json.dumps({"copied_to": STATIC, **subs}, indent=1))


if __name__ == "__main__":
    main()
