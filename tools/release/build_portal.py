def esc(s):
    return html.escape(str(s or ""), quote=True)


def autolink(text):
    """Escape, then turn bare URLs into links."""
    out = esc(text)
    return re.sub(r"(https?://[^\s<>&\"]+[^\s<>&\".,)])",
                  r'<a href="\1">\1</a>', out)


def access_case(row):
    """The four access cases, mirroring moveatlas/registry.py (kept in
    sync by hand so the portal stays stdlib-only)."""
    redist = (row.get("redistribution") or "").strip().lower()
    status = (row.get("status") or "")
    lic = (row.get("license") or "").lower()
    if lic.startswith("private"):
        return "local_only"
    if redist.startswith("yes"):
        return "hosted"
    up = status.upper()
    if ("DOCUMENTED BARRIER" in up or "WRITTEN OFF" in up
            or "HUMAN QUEUE" in up):
        return "barrier"
    return "recipe"


