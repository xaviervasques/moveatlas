    with open(os.path.join(out, "index.html"), "w", encoding="utf-8",
              newline="\n") as f:
        f.write(page("MoveAtlas Data Portal", body, 0,
                     subtitle="Public movement and movement-disorder datasets, "
                     "documented, licensed and citable. The data catalogue of "
                     "the MoveAtlas atlas."))
    # citations.bib served as a download next to the index
    with open(os.path.join(out, "citations.bib"), "w", encoding="utf-8",
              newline="\n") as f:
        f.write(bib_text)

