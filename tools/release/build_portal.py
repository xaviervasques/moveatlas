def parse_cells(cellstr):
    """'B2, D3; M2' -> (['B2','D3'], ['M2'])."""
    toks = re.findall(r"\b([A-E]\d|M\d{1,2})\b", cellstr or "")
    cells = [t for t in toks if not t.startswith("M") and t in CELLS]
    mods = [t for t in toks if t.startswith("M") and t in MODS]
    seen = set()
    cells = [c for c in cells if not (c in seen or seen.add(c))]
    seen = set()
    mods = [m for m in mods if not (m in seen or seen.add(m))]
    return cells, mods


def render_datacard(md_text):
    """The datacard dialect -> HTML: '# title' dropped (the page has its own
    header), '- key: value' bullets with indented continuations -> a <dl>,
    anything else -> a paragraph. No guessing beyond that."""
    items, extras = [], []
    cur = None
    for raw in md_text.splitlines():
        if raw.startswith("# "):
            continue
        m = re.match(r"- ([^:]{1,40}):\s?(.*)$", raw)
        if m:
            cur = [m.group(1).strip(), m.group(2)]
            items.append(cur)
        elif raw.startswith(("  ", "\t")) and cur is not None:
            cur[1] += " " + raw.strip()
        elif raw.strip():
            cur = None
            extras.append(raw.strip())
        else:
            cur = None
    dl = "".join(f"<dt>{esc(k)}</dt><dd>{autolink(v)}</dd>" for k, v in items)
    out = f'<dl class="card">{dl}</dl>' if items else ""
    out += "".join(f"<p>{autolink(x)}</p>" for x in extras)
    return out


def tier_badge(action):
    tier, cls, _ = TIERS.get(action, ("2", "verify", ""))
    label = {"hosted": "tier 1 · hosted copy planned",
             "pointer": "tier 2 · pointer only",
             "verify": "tier 2 · licence to verify",
             "private": "tier 3 · collaboration only"}[cls]
    return f'<span class="badge b-{cls}">{esc(label)}</span>'


def bibtex_for(ds_id, bib_text):
    """Extract this dataset's entries from citations.bib by bibkey prefix."""
    out = []
    for m in re.finditer(r"@\w+\{([^,]+),.*?\n\}\n", bib_text, re.S):
        if m.group(1).startswith(ds_id + "_"):
            out.append(m.group(0).rstrip())
    return "\n\n".join(out)


def fmt_citation(row):
    au = row["authors"].split(";")
    au_s = esc(au[0].strip()) + (" et al." if len(au) > 1 else "")
    year = esc(row["year"]) or "n.d."
    venue = f' <i>{esc(row["venue"])}</i>.' if row["venue"] else ""
    doi = (f' <a href="https://doi.org/{esc(row["doi"])}">doi:{esc(row["doi"])}</a>'
           if row["doi"] else "")
    return (f'<div><span class="kind">{esc(row["kind"])}</span><br>'
            f'{au_s} ({year}). {esc(row["title"])}.{venue}{doi}</div>')


